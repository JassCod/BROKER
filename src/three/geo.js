const SCALE = 0.14;
const CENTER = [134, -27];

// Equirectangular projection into scene units, centred on the continent.
export const project = (lon, lat) => [(lon - CENTER[0]) * SCALE, (lat - CENTER[1]) * SCALE];

export function pointInPolygon([x, y], poly) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
